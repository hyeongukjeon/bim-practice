def option_detail_from_context(key: str, item: dict, index: int, existing: str) -> str:
    option = item["options"][index]
    question = item["question"]
    exact = exact_option_detail(option)
    keyword = keyword_option_detail(question, option)
    detail = exact or keyword or existing
    if len(detail) < 35:
        detail = existing if len(existing) >= 35 else answer_detail_from_item(item)
    return detail


def detailed_answer_explanation(item: dict) -> str:
    key = f"{source_key(item)}:{item['number']}"
    base = ANSWER_EXPLANATIONS.get(key, answer_detail_from_item(item))
    negative = is_negative_question(item["question"])
    explanations = item.get("optionExplanations") or []
    blocks = [f"핵심: {base}"]

    for index, option in enumerate(item["options"]):
        existing = clean_option_detail(explanations[index]) if index < len(explanations) else ""
        detail = option_detail_from_context(key, item, index, existing)
        is_answer = index == item["answer"]
        if negative and is_answer:
            detail = f"{detail} 문항이 '옳지 않은 것' 또는 '아닌 것'을 묻고 있으므로, 이 틀린 설명이 정답입니다."
        elif negative:
            detail = f"{detail} 그래서 이 보기는 실제 기능 설명으로는 맞는 편이라 정답이 아니라 오답 처리됩니다."
        elif is_answer:
            detail = f"{detail} 문제에서 묻는 기능이나 개념과 직접 일치하므로 정답입니다."
        else:
            detail = f"{detail} 문제에서 묻는 정답 기능과는 역할이나 위치가 다르므로 오답입니다."
        blocks.append(f"{MARKS[index]} {'정답' if is_answer else '오답'}: {option}\n{detail}")

    return "\n\n".join(blocks)


def apply_refinements(data: dict) -> None:
    for item in data["questions"]:
        key = f"{source_key(item)}:{item['number']}"
        if key in ANSWER_OVERRIDES:
            item["answer"] = ANSWER_OVERRIDES[key]
        if key not in OVERRIDES:
            continue
        details = OVERRIDES[key]
        if len(details) != len(item["options"]):
            raise ValueError(f"{key} override has {len(details)} details")
        item["optionExplanations"] = [
            f"{MARKS[index]} {'정답' if index == item['answer'] else '오답'}: {detail}"
            for index, detail in enumerate(details)
        ]
        item["explanation"] = "\n".join(item["optionExplanations"])

    for item in data["questions"]:
        item["answerExplanation"] = detailed_answer_explanation(item)
        item["explanation"] = item["answerExplanation"]


def main() -> None:
    data = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    apply_refinements(data)
    DATA_PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    JS_PATH.write_text(
        "window.BIM_QUESTIONS = "
        + json.dumps(data, ensure_ascii=False, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )


